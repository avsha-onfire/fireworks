describe('isDataFile', () => {
  it('accepts CSV, TSV and JSON files by extension or MIME type', () => {
    expect(isDataFile({ name: 'deals.csv' })).toBe(true);
    expect(isDataFile({ name: 'DEALS.CSV', type: '' })).toBe(true);
    expect(isDataFile({ name: 'leads.tsv', type: 'text/tab-separated-values' })).toBe(true);
    expect(isDataFile({ name: 'accounts.json', type: 'application/json' })).toBe(true);
    expect(isDataFile({ name: 'pasted', type: 'text/csv;charset=utf-8' })).toBe(true);
  });

  it('treats a CSV file that Windows reports as an Excel document as data', () => {
    const file = { name: 'report.csv', type: 'application/vnd.ms-excel' };

    expect(isDataFile(file)).toBe(true);
    expect(isSpreadsheetFile(file)).toBe(false);
  });

  it('rejects everything else', () => {
    expect(isDataFile({ name: 'screenshot.png', type: 'image/png' })).toBe(false);
    expect(isDataFile({ name: 'notes.txt', type: 'text/plain' })).toBe(false);
    expect(isDataFile({ name: 'csv' })).toBe(false);
    expect(isDataFile({ name: 'pipeline.xlsx', type: 'text/csv' })).toBe(false);
  });

  it('does not throw on malformed input', () => {
    expect(isDataFile(undefined as never)).toBe(false);
    expect(isDataFile({ name: 42, type: null } as never)).toBe(false);
    expect(isSpreadsheetFile(null as never)).toBe(false);
  });
});

describe('isSpreadsheetFile', () => {
  it('recognises Excel workbooks by extension or MIME type', () => {
    const workbookType = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';

    expect(isSpreadsheetFile({ name: 'pipeline.xlsx' })).toBe(true);
    expect(isSpreadsheetFile({ name: 'Pipeline.XLS' })).toBe(true);
    expect(isSpreadsheetFile({ name: 'download', type: workbookType })).toBe(true);
    expect(isSpreadsheetFile({ name: 'deals.csv', type: 'text/csv' })).toBe(false);
    expect(isSpreadsheetFile({ name: 'logo.png', type: 'image/png' })).toBe(false);
  });
});

describe('describeDataFile: block format', () => {
  const summary = describeDataFile('deals.csv', 'Stage,Amount\nOpen,100\nWon,250\n');

  it('wraps the summary in the data-file fence so other code can find and strip it', () => {
    expect(summary.startsWith(`${DATA_FILE_BLOCK_START}\n`)).toBe(true);
    expect(summary.endsWith(`\n${DATA_FILE_BLOCK_END}`)).toBe(true);
    expect(extractDataFileSummaries(`Build a pipeline dashboard.\n\n${summary}`)).toEqual([summary]);
    expect(stripDataFileSummaries(`Build a pipeline dashboard.\n\n${summary}`)).toBe('Build a pipeline dashboard.');
  });

  it('starts with the fixed provenance line and lists rows, columns, format and one line per column', () => {
    expect(bodyLines(summary)).toEqual([
      FIRST_LINE('deals.csv'),
      'Rows: 2',
      'Columns: 2',
      'Format: comma-separated values.',
      '- Stage — text, 3–4 chars — 100% filled — 2 distinct',
      '- Amount — number (1234) — 100% filled — 2 distinct — e.g. 100 | 250',
    ]);
  });

  it('reports whether the file could be read', () => {
    expect(inspectDataFile('deals.csv', 'Stage,Amount\nOpen,100\n')).toEqual({
      summary: describeDataFile('deals.csv', 'Stage,Amount\nOpen,100\n'),
      readable: true,
    });
    expect(inspectDataFile('deals.csv', '').readable).toBe(false);
  });
});

